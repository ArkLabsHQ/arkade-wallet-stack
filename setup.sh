#!/usr/bin/env bash
# Arkade Wallet Stack — one-command setup.
# Checks prerequisites, configures .env (generating secrets), and launches.
set -euo pipefail

ROOT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
cd "$ROOT_DIR"
# shellcheck source=scripts/lib.sh
. "$ROOT_DIR/scripts/lib.sh"

ASSUME_YES=0

usage() {
	cat <<'EOF'
Arkade Wallet Stack — one-command setup.

Usage:
  ./setup.sh          Interactive: check prerequisites, configure .env, launch.
  ./setup.sh --yes    Non-interactive: take REQUIRED values from environment
                      variables (BASE_DOMAIN, ACME_EMAIL, ARKADE_SERVER_URL,
                      COVCLAIM_ARK_URL, COVCLAIM_EMULATOR_URL, ESPLORA_URL),
                      generate secrets, and launch.
  ./setup.sh --help   Show this help.
EOF
}

for arg in "$@"; do
	case "$arg" in
		--yes|-y)  ASSUME_YES=1 ;;
		--help|-h) usage; exit 0 ;;
		*)         die "unknown argument: $arg (try --help)" ;;
	esac
done

# --- 1. prerequisites --------------------------------------------------------
ensure_prereqs() {
	local missing=0
	have git    || { warn "git not found";    missing=1; }
	have docker || { warn "docker not found"; missing=1; }
	if have docker && ! docker compose version >/dev/null 2>&1; then
		warn "docker compose plugin not found"; missing=1
	fi
	if [ "$missing" -eq 1 ]; then
		if [ "$ASSUME_YES" -eq 1 ] || confirm "Install missing prerequisites now (git, docker, compose)?"; then
			bash "$ROOT_DIR/scripts/install-prereqs.sh"
		else
			die "prerequisites missing; install them and re-run"
		fi
	fi
	docker info >/dev/null 2>&1 \
		|| die "cannot reach the docker daemon (is it running? if you were just added to the 'docker' group, log out and back in)"
	ok "prerequisites present"
}

# --- 2. configuration --------------------------------------------------------
# value <VARNAME> <prompt text> <default> : resolve one config value. In --yes
# mode it comes from the environment variable (or the default); otherwise the
# user is prompted with the default pre-filled.
value() {
	local var=$1 text=$2 def=$3 cur=''
	[ -n "${!var:-}" ] && cur=${!var}
	if [ "$ASSUME_YES" -eq 1 ]; then
		printf '%s' "${cur:-$def}"
	else
		prompt_default "$text" "${cur:-$def}"
	fi
}

configure() {
	if [ -f .env ]; then
		if [ "$ASSUME_YES" -eq 1 ] || confirm ".env already exists. Keep it as-is?" Y; then
			[ -f secrets/fulmine_password ] \
				|| warn "secrets/fulmine_password is missing — the stack will not start until it is restored"
			ok "keeping existing .env"
			return
		fi
		cp .env ".env.bak.$(date +%s)" && warn "backed up existing .env"
	fi

	log "Configuring your stack (press Enter to accept each default)"
	local base_domain acme_email ark_url covclaim_ark covclaim_emu esplora boltz_url fee
	base_domain=$(value BASE_DOMAIN         "Base domain (all subdomains derive from this)" "example.com")
	acme_email=$(value  ACME_EMAIL          "Email for Let's Encrypt TLS"                   "admin@${base_domain}")
	ark_url=$(value     ARKADE_SERVER_URL   "Arkade Service URL (fulmine)"                  "https://arkd.${base_domain}")
	covclaim_ark=$(value COVCLAIM_ARK_URL   "Arkade Service gRPC address (covclaim)"        "arkd.${base_domain}:7070")
	covclaim_emu=$(value COVCLAIM_EMULATOR_URL "Covenant emulator gRPC address (covclaim)"  "emulator.${base_domain}:7073")
	esplora=$(value     ESPLORA_URL         "Esplora chain API base URL"                    "https://mempool.space/api")
	boltz_url=$(value   BOLTZ_API_URL       "Boltz API URL (payment-push)"                  "https://api.boltz.mutinynet.arkade.sh")
	fee=$(value         FULMINE_DELEGATE_FEE "Delegate fee in satoshis"                     "0")

	log "Generating secrets..."
	local lnurl_key covclaim_key pg_pass
	lnurl_key=$(gen_hex 32)
	covclaim_key=$(gen_hex 32)
	pg_pass=$(gen_hex 24)

	umask 077
	mkdir -p secrets
	gen_b64 24 > secrets/fulmine_password
	chmod 600 secrets/fulmine_password

	cat > .env <<EOF
# Generated by setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
BASE_DOMAIN=${base_domain}
ACME_EMAIL=${acme_email}
ARKADE_SERVER_URL=${ark_url}
COVCLAIM_ARK_URL=${covclaim_ark}
COVCLAIM_EMULATOR_URL=${covclaim_emu}
ESPLORA_URL=${esplora}
BOLTZ_API_URL=${boltz_url}
ARKADE_NETWORK=bitcoin
NTFY_BASE_URL=https://ntfy.sh
LNURL_TOKEN_ENCRYPTION_KEY=${lnurl_key}
COVCLAIM_SECRET_KEY=${covclaim_key}
POSTGRES_PASSWORD=${pg_pass}
FULMINE_DELEGATE_FEE=${fee}
EOF
	chmod 600 .env
	ok "wrote .env and secrets/fulmine_password"
}

# --- 3. launch ---------------------------------------------------------------
launch() {
	log "Pulling images..."
	docker compose pull --ignore-buildable
	log "Building the edge and starting the stack (first run can take a few minutes)..."
	docker compose up -d --build
	ok "stack is up"
}

# --- 4. post-launch guidance -------------------------------------------------
post() {
	local d; d=$(grep -E '^BASE_DOMAIN=' .env | cut -d= -f2-)
	printf '\n'
	log "Almost done — a couple of manual steps remain:"
	cat <<EOF

  1. DNS — create these A records pointing at THIS server's public IP:
        delegate.${d}      lnurl.${d}      backup.${d}      covclaim.${d}
     Caddy issues TLS certificates automatically once the names resolve.

  2. Create the fulmine wallet (one time only). The delegate stays offline
     until a wallet exists and is unlocked. Your generated wallet password:
        cat secrets/fulmine_password
     Reach fulmine's admin UI (bound to loopback) over an SSH tunnel, create
     and unlock the wallet with that password:
        ssh -L 7001:127.0.0.1:7001 <this-server>   # then open http://localhost:7001
     After it is created once, fulmine auto-unlocks on every restart.

  Check status any time with:  docker compose ps   |   docker compose logs -f

EOF
}

main() {
	ensure_prereqs
	configure
	launch
	post
}
main "$@"
